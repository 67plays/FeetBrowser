C     The tables of ISO/IEC 14496-3: the twelve Huffman codebooks, the
C     scalefactor band offsets, and the constants derived from them.
C
C     Two kinds of number live here.  The first kind is arbitrary -- a
C     codeword length, a band boundary -- and is written out as DATA
C     because there is no rule to derive it from.  The second kind has a
C     rule, and is computed at startup rather than listed: the value each
C     spectral codeword stands for is its position in a base-N counter
C     (IPHDEC), x^(4/3) is a power, and the windows and twiddle factors
C     are sines.  Listing those would be a thousand numbers nobody could
C     check against anything.
C
C     The codebooks were checked before they were written out.  Each of
C     the twelve has a Kraft sum of exactly one and is prefix free, which
C     together mean the tree IPTHUF builds from them is complete: every
C     bit pattern decodes, so a corrupt stream produces a wrong number
C     rather than a walk off the end of an array.
C
C     The tables are built into COMMON once by IPTINI, from local DATA
C     arrays.  DATA cannot initialise COMMON outside a BLOCK DATA, and a
C     BLOCK DATA holding a thousand values in twelve blocks is a file
C     nobody would edit twice; copying is a few microseconds at reset.

C     Everything, in the order the decoder needs it.
      SUBROUTINE IPTINI
      IMPLICIT NONE
      CALL IPTHUF
      CALL IPTSWB
      CALL IPTDSP
      RETURN
      END

