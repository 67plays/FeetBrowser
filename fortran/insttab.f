C     -- the numbers with rules -------------------------------------------
C
C     x^(4/3) for every quantised magnitude a stream may carry, the two
C     window shapes at both lengths, and the twiddle factors the IMDCT's
C     FFT turns on.  All of it is arithmetic, so all of it is computed.
C
C     The Kaiser-Bessel derived window is 4.6.11.3: a Kaiser window of
C     N/2+1 points, cumulatively summed and square rooted.  Writing it out
C     that way makes the Princen-Bradley condition w(n)^2 + w(N-1-n)^2 = 1
C     a property of the definition rather than a coincidence, because the
C     numerator sums of any two mirrored points add up to the denominator.
      SUBROUTINE IPTDSP
      IMPLICIT NONE
      INCLUDE 'instcom.inc'
      INTEGER I, K, J, R
      DOUBLE PRECISION P, A
      P = 4.0D0 * ATAN(1.0D0)

      X43(0) = 0.0D0
      DO 10 I = 1, MXQNT
         X43(I) = DBLE(I) ** (4.0D0 / 3.0D0)
   10 CONTINUE

C     2^((sf-100)/4), the gain a scalefactor stands for.  Scalefactors
C     are eight bit, and the largest of them is 2^38.75, which is a
C     perfectly ordinary double and an inaudible one.
      DO 20 I = 0, 255
         GAINT(I) = 2.0D0 ** (0.25D0 * DBLE(I - 100))
   20 CONTINUE

C     The sine windows: the rising half of each, which is all the decoder
C     ever needs -- the falling half is the same numbers backwards.
      DO 30 I = 0, 1023
         WSINL(I) = SIN(P / 2048.0D0 * (DBLE(I) + 0.5D0))
   30 CONTINUE
      DO 40 I = 0, 127
         WSINS(I) = SIN(P / 256.0D0 * (DBLE(I) + 0.5D0))
   40 CONTINUE

C     The KBD windows, alpha = 4 long and 6 short.
      CALL IPTKBD(WKBDL, 1024, 4.0D0)
      CALL IPTKBD(WKBDS, 128, 6.0D0)

C     Twiddle factors.  The IMDCT of 2M points is a DCT-IV of M points,
C     which is a complex FFT of M/2 points with a rotation by
C     -pi(k + 1/8)/M either side of it -- the same rotation on both
C     sides, so one table serves both.  M is 1024 for a long window and
C     128 for a short one.
      DO 50 I = 0, 511
         A = -P * (DBLE(I) + 0.125D0) / 1024.0D0
         PTLR(I) = COS(A)
         PTLI(I) = SIN(A)
   50 CONTINUE
      DO 60 I = 0, 63
         A = -P * (DBLE(I) + 0.125D0) / 128.0D0
         PTSR(I) = COS(A)
         PTSI(I) = SIN(A)
   60 CONTINUE
      DO 70 I = 0, 255
         A = -2.0D0 * P * DBLE(I) / 512.0D0
         TWLR(I) = COS(A)
         TWLI(I) = SIN(A)
   70 CONTINUE
      DO 80 I = 0, 31
         A = -2.0D0 * P * DBLE(I) / 64.0D0
         TWSR(I) = COS(A)
         TWSI(I) = SIN(A)
   80 CONTINUE

C     Bit reversal, the permutation the iterative FFT starts from.
      DO 100 I = 0, 511
         R = 0
         K = I
         DO 90 J = 1, 9
            R = IOR(ISHFT(R, 1), IAND(K, 1))
            K = ISHFT(K, -1)
   90    CONTINUE
         BRL(I) = R
  100 CONTINUE
      DO 120 I = 0, 63
         R = 0
         K = I
         DO 110 J = 1, 6
            R = IOR(ISHFT(R, 1), IAND(K, 1))
            K = ISHFT(K, -1)
  110    CONTINUE
         BRS(I) = R
  120 CONTINUE

      RETURN
      END

C     One KBD window half of N points.  I0 is the modified Bessel
C     function of the first kind, summed until the terms stop mattering;
C     its argument here never exceeds 6*pi, where the series converges in
C     about forty terms.
      SUBROUTINE IPTKBD(W, N, ALPHA)
      IMPLICIT NONE
      INTEGER N
      DOUBLE PRECISION W(0:*), ALPHA
      DOUBLE PRECISION KB(0:1024), P, X, S, TOT, IPTBI0
      EXTERNAL IPTBI0
      INTEGER I
      P = 4.0D0 * ATAN(1.0D0)
      TOT = 0.0D0
      DO 10 I = 0, N
         X = 2.0D0 * DBLE(I) / DBLE(N) - 1.0D0
         KB(I) = IPTBI0(P * ALPHA * SQRT(1.0D0 - X * X))
         TOT = TOT + KB(I)
   10 CONTINUE
      S = 0.0D0
      DO 20 I = 0, N - 1
         S = S + KB(I)
         W(I) = SQRT(S / TOT)
   20 CONTINUE
      RETURN
      END

      DOUBLE PRECISION FUNCTION IPTBI0(X)
      IMPLICIT NONE
      DOUBLE PRECISION X, T, S
      INTEGER K
      S = 1.0D0
      T = 1.0D0
      DO 10 K = 1, 60
         T = T * (X / (2.0D0 * DBLE(K))) ** 2
         S = S + T
         IF (T .LT. 1.0D-18 * S) GOTO 20
   10 CONTINUE
   20 IPTBI0 = S
      RETURN
      END

