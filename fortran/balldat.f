C     The tables that have no formula: the Huffman code tables, the
C     scalefactor band boundaries, the pre-emphasis table and the 512-tap
C     synthesis window.
C
C     Every number here was taken from the ISO dist10 reference software
C     and then checked against FFmpeg, libmad, mpg123, minimp3 and LAME.
C     They agree everywhere except one entry: the long scalefactor band
C     boundary 18 at 24 kHz, where the reference software says 330 and
C     every other decoder says 332.  332 is used, because it is what the
C     printed standard says, what our ground truth decodes with, and what
C     makes a 24 kHz granule's bits add up to the length its side
C     information promised.  A decoder that took 330 would put two
C     coefficients in the wrong band on one of the nine sampling
C     frequencies and sound very slightly wrong there and nowhere else,
C     which is the kind of bug that survives a long time.
C
C     The MPEG-2.5 rows -- 11025, 12000 and 8000 -- are in no standard
C     document at all.  They are the Fraunhofer extension, and they are
C     here because a great many files use them.
C
C     The tables are built into COMMON once by BLTDAT, from local DATA
C     arrays.  DATA cannot initialise COMMON outside a BLOCK DATA, and a
C     BLOCK DATA holding four thousand values would be a file nobody
C     would edit twice; copying is a few microseconds at reset.

      SUBROUTINE BLTDAT
      IMPLICIT NONE
      CALL BLTHUF
      CALL BLTSWB
      CALL BLTWIN
      RETURN
      END

